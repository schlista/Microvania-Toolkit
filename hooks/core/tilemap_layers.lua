-- hooks/core/tilemap_layers.lua
--
-- Bake-time manifest of every room tilemap's layer ids, written by Create
-- Rooms to developer/config/room_tilemap_layers_generated.lua.
--
-- Why: Defold's tilemap API cannot list a tilemap's layers (there is no
-- tilemap.get_layers), and probing a missing layer with tilemap.get_tile logs
-- "ERROR:GAMESYS: Could not find layer" even inside pcall. Runtime code that
-- needs to know which layers exist reads this manifest instead.
--
-- Pure Lua: no editor or Defold globals, so it runs headless and in tests.

local ResourceText = require "mvtk.editor.resource_text"
local M = {}

M.MANIFEST_PATH = "developer/config/room_tilemap_layers_generated.lua"

--- Ordered layer ids declared in a .tilemap (protobuf text).
function M.parse_layer_ids(text)
    local ids = {}
    if type(text) ~= "string" then return ids end
    -- Reuse the resource parser so field ordering, escaping, and comments obey
    -- the same rules as the other resource editors.
    local doc = ResourceText.parse(text)
    for _, layer in ipairs(ResourceText.all(doc.root, "layers")) do
        local id = layer.node and ResourceText.value(layer.node, "id")
        if type(id) == "string" and id ~= "" then ids[#ids + 1] = id end
    end
    return ids
end

local function quote(s)
    return string.format("%q", tostring(s))
end

--- Serialize { [room_id] = { layer ids... } } deterministically.
function M.generate(rooms)
    local room_ids = {}
    for room_id in pairs(rooms or {}) do room_ids[#room_ids + 1] = room_id end
    table.sort(room_ids)
    local out = {
        "-- developer/config/room_tilemap_layers_generated.lua",
        "-- GENERATED by Create Rooms from each room's .tilemap. Do not edit.",
        "-- Runtime code checks layer existence here: Defold cannot list tilemap",
        "-- layers, and probing a missing layer logs an engine error.",
        "return {",
        "    rooms = {",
    }
    for _, room_id in ipairs(room_ids) do
        local layers = {}
        for _, id in ipairs(rooms[room_id] or {}) do layers[#layers + 1] = quote(id) end
        out[#out + 1] = string.format("        [%s] = { %s },", quote(room_id), table.concat(layers, ", "))
    end
    out[#out + 1] = "    },"
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

--- Build the manifest for room ids, reading each room's tilemap text via
-- read_tilemap(room_id) -> string|nil. Rooms without a tilemap are omitted.
function M.build(room_ids, read_tilemap)
    local rooms = {}
    for _, room_id in ipairs(room_ids or {}) do
        local ok, text = pcall(read_tilemap, room_id)
        if ok and type(text) == "string" then
            rooms[room_id] = M.parse_layer_ids(text)
        end
    end
    return rooms
end

return M
