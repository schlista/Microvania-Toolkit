-- hooks/core/chest_inline_contents.lua
--
-- Chests bake their Tiled `rewards.contents` (e.g. "currency:25,health_small:1")
-- into a text go.property. Keep the inline-contents registry for hash callers;
-- text values resolve directly at runtime. This module reads both old HASH and
-- rebuilt TEXT properties and rebuilds developer/config/chest_inline_contents.lua
-- after Create Rooms. Pure Lua; runs headless and in tests.

local M = {}

M.CONFIG_PATH = "developer/config/chest_inline_contents.lua"

--- Inline contents strings (contain ':') from one .collection text.
function M.collect(collection_text, into)
    into = into or {}
    if type(collection_text) ~= "string" then return into end
    for value in collection_text:gmatch('id:%s*"loot_table"%s*value:%s*"([^"]*)"') do
        local trimmed = value:match("^%s*(.-)%s*$")
        if trimmed:find(":", 1, true) then into[trimmed] = true end
    end
    return into
end

--- Deterministic Lua source for the config file.
function M.generate(set)
    local list = {}
    for value in pairs(set or {}) do list[#list + 1] = value end
    table.sort(list)
    local out = { "-- developer/config/chest_inline_contents.lua (generated by hooks.editor_script)", "return {" }
    for _, value in ipairs(list) do out[#out + 1] = string.format("    %q,", value) end
    out[#out + 1] = "}"
    return table.concat(out, "\n") .. "\n"
end

return M
