-- hooks/core/elevator_config.lua
--
-- Deterministic serializer for the runtime elevator authoring index generated
-- by Create Rooms. The editor manifest contains diagnostics and source-only
-- bookkeeping; this module emits only the geometry/settings needed after the
-- final world layout has positioned every streamed room.

local M = {}

local MARKER_FIELDS = {
    "elevator_id",
    "room_id",
    "object_id",
    "source_key",
    "name",
    "kind",
    "node_kind",
    "node_id",
    "stop",
    "door_id",
    "start_node_id",
    "local_x",
    "local_y",
    "width",
    "height",
    "properties",
}

local function clone_plain(value, seen)
    local kind = type(value)
    if kind == "string" or kind == "number" or kind == "boolean" then return value end
    if kind ~= "table" then return nil end
    seen = seen or {}
    if seen[value] then return nil end
    seen[value] = true
    local result = {}
    for key, child in pairs(value) do
        local clean_key = clone_plain(key, seen)
        local clean_child = clone_plain(child, seen)
        if clean_key ~= nil and clean_child ~= nil then result[clean_key] = clean_child end
    end
    seen[value] = nil
    return result
end

local function marker_record(marker)
    local result = {}
    for _, field in ipairs(MARKER_FIELDS) do
        if marker and marker[field] ~= nil then
            result[field] = clone_plain(marker[field])
        end
    end
    return result
end

function M.runtime_manifest(manifest)
    local runtime = {
        version = tonumber(manifest and manifest.version) or 1,
        ordered_ids = {},
        elevators = {},
    }
    for _, elevator_id in ipairs((manifest and manifest.ordered_ids) or {}) do
        local authored = manifest.elevators and manifest.elevators[elevator_id]
        if authored and authored.valid ~= false then
            local entry = {
                id = authored.id or elevator_id,
                resource_key = authored.resource_key,
                settings = clone_plain(authored.settings or {}),
                controller = marker_record(authored.controller),
                nodes = {},
            }
            for _, node in ipairs(authored.nodes or {}) do
                entry.nodes[#entry.nodes + 1] = marker_record(node)
            end
            runtime.ordered_ids[#runtime.ordered_ids + 1] = elevator_id
            runtime.elevators[elevator_id] = entry
        end
    end
    return runtime
end

local LUA_KEYWORDS = {
    ["and"] = true, ["break"] = true, ["do"] = true, ["else"] = true,
    ["elseif"] = true, ["end"] = true, ["false"] = true, ["for"] = true,
    ["function"] = true, ["if"] = true, ["in"] = true, ["local"] = true,
    ["nil"] = true, ["not"] = true, ["or"] = true, ["repeat"] = true,
    ["return"] = true, ["then"] = true, ["true"] = true, ["until"] = true,
    ["while"] = true,
}

local function is_array(value)
    local count = 0
    for key in pairs(value) do
        if type(key) ~= "number" or key < 1 or key ~= math.floor(key) then return false end
        count = count + 1
    end
    return count == #value
end

local function quote(value)
    return string.format("%q", tostring(value))
end

local serialize

local function key_text(key)
    if type(key) == "string" and key:match("^[%a_][%w_]*$") and not LUA_KEYWORDS[key] then
        return key
    end
    return "[" .. serialize(key, "") .. "]"
end

serialize = function(value, indent)
    local kind = type(value)
    if kind == "string" then return quote(value) end
    if kind == "boolean" or kind == "number" then return tostring(value) end
    if kind ~= "table" then return "nil" end

    local next_indent = indent .. "    "
    local lines = { "{" }
    if is_array(value) then
        for _, child in ipairs(value) do
            lines[#lines + 1] = next_indent .. serialize(child, next_indent) .. ","
        end
    else
        local keys = {}
        for key in pairs(value) do keys[#keys + 1] = key end
        table.sort(keys, function(a, b)
            local ta, tb = type(a), type(b)
            if ta ~= tb then return ta < tb end
            return tostring(a) < tostring(b)
        end)
        for _, key in ipairs(keys) do
            lines[#lines + 1] = string.format(
                "%s%s = %s,", next_indent, key_text(key), serialize(value[key], next_indent))
        end
    end
    lines[#lines + 1] = indent .. "}"
    return table.concat(lines, "\n")
end

function M.generate(manifest)
    local runtime = M.runtime_manifest(manifest or {})
    return table.concat({
        "-- developer/config/elevators_generated.lua",
        "-- GENERATED by Create Rooms from elevator/elevator_node Tiled templates.",
        "-- Do not edit; change the templates in Tiled and run Prepare & Check.",
        "return " .. serialize(runtime, ""),
        "",
    }, "\n")
end

return M
