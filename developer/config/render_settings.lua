-- developer/config/render_settings.lua
-- ============================================================================
-- RENDER ORDER SETTINGS
-- ============================================================================
--
-- These values define the major 2D z-bands used by the toolkit.
-- Adjust them here if you want to change which visuals draw in front.
--
-- IMPORTANT:
-- - Higher z values render in front of lower z values for the default 2D pass.
-- - Keep these values inside the default 2D camera clip space. The toolkit
--   camera currently renders with a near/far range of about -1..1.
-- - Keep large gaps between major bands so gameplay props, the player, and
--   imported foreground art do not overlap by accident.
-- - Foreground image/object layers generated from Tiled use the foreground
--   settings below. Regular gameplay objects can continue using their own
--   local z offsets inside their prefab files.
-- ============================================================================

return {
    -- Player root game object z.
    -- Set this above normal gameplay visuals so the player stays in front of
    -- platforms, save points, grapple points, and other common props.
    player_z = 0.90,

    -- Sprite z for enemies generated by Sync Enemy Art (Prepare & Check).
    -- Room tile layers (background, environment, foreground) bake at about
    -- 0.0007-0.0009, so enemies at 0 would hide behind a painted background.
    -- Keep this above 0.01 (tile layers and object art) and below player_z.
    -- Run Prepare & Check after changing it to rewrite the enemy prefabs.
    enemy_z = 0.50,

    -- Boss root depth (unitless z), above tile layers/object art and below
    -- summoned enemies and the player. Safe range: -0.99..enemy_z; use >0.01
    -- to keep the boss visible over painted backgrounds.
    boss_z = 0.45,

    -- The z used for the first imported foreground image/object layer that sits
    -- above tile layers in Tiled. Keep this above player_z so authored
    -- foreground art still renders over the player.
    foreground_base_z = 0.96,

    -- Additional z offset per imported foreground layer above the tilemap.
    -- This preserves Tiled's layer stacking order for multiple foreground
    -- layers without collapsing them into the same band.
    foreground_layer_step = 0.005,

    -- Small per-object offset within a single imported foreground object layer.
    -- This preserves object draw order inside that layer while keeping every
    -- object inside the same major foreground band.
    foreground_object_step = 0.00005,
}
