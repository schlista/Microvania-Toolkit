-- developer/tools/ability_defaults_writer.lua
--
-- Shared ability-default resolution for Project > Game Settings... and headless tools.
-- Ability ids always come from developer/config/abilities.lua so adding a new
-- registry entry cannot silently omit it from generated or runtime defaults.

local AbilityConfig = require "developer.config.abilities"

local M = {}

local CATEGORY_PRIORITY = {
    movement = 1,
    combat = 2,
    defensive = 3,
}

local function registry_from(source)
    source = source or AbilityConfig
    return source.abilities or source
end

local function normalized_category(definition)
    local category = definition and definition.category
    if type(category) ~= "string" or category:match("^%s*$") then
        return nil
    end
    return category:lower()
end

local function category_sort_key(category)
    if category == nil then
        return 3, ""
    end
    local priority = CATEGORY_PRIORITY[category]
    if priority then
        return 1, string.format("%02d", priority)
    end
    return 2, category
end

local function category_label(category)
    if category == nil then
        return "Other"
    end
    return (category:gsub("^%l", string.upper):gsub("_", " "))
end

function M.toggle_key(ability_id)
    return tostring(ability_id) .. "_enabled"
end

function M.ordered_abilities(source)
    local registry = registry_from(source)
    local entries = {}
    for ability_id, definition in pairs(registry) do
        entries[#entries + 1] = {
            id = tostring(ability_id),
            definition = type(definition) == "table" and definition or {},
            category = normalized_category(definition),
        }
    end

    table.sort(entries, function(a, b)
        local a_group, a_key = category_sort_key(a.category)
        local b_group, b_key = category_sort_key(b.category)
        if a_group ~= b_group then return a_group < b_group end
        if a_key ~= b_key then return a_key < b_key end
        return a.id < b.id
    end)
    return entries
end

local function resolved_value(ability_id, definition, preset)
    local value = preset[M.toggle_key(ability_id)]
    if value ~= nil then
        return value and true or false
    end

    -- Compatibility with older custom presets that expressed double-jump
    -- availability only through the number of extra air jumps.
    if ability_id == "double_jump" then
        local air_jumps = preset.air_jumps
        if air_jumps == nil then air_jumps = 1 end
        return (tonumber(air_jumps) or 0) > 0
    end

    return definition.starts_unlocked == true
end

function M.resolve(preset, source)
    preset = preset or {}
    local values = {}
    for _, entry in ipairs(M.ordered_abilities(source)) do
        values[entry.id] = resolved_value(entry.id, entry.definition, preset)
    end
    return values
end

function M.preset_from_defaults(defaults, source)
    local authored = defaults and (defaults.abilities or defaults) or {}
    local preset = {}
    for _, entry in ipairs(M.ordered_abilities(source)) do
        local value = authored[entry.id]
        if value == nil then
            value = entry.definition.starts_unlocked == true
        end
        preset[M.toggle_key(entry.id)] = value and true or false
    end
    return preset
end

local HEADER = [[-- ============================================================================
-- developer/config/ability_defaults.lua
-- ============================================================================
-- SINGLE SOURCE OF TRUTH for which abilities are unlocked at game start.
-- Edit this baseline directly, or set starting unlocks in Project > Game Settings... > Abilities.
-- Game Settings saves creator_settings.lua overrides and preserves this baseline.
--
-- true  = Ability is available from the start
-- false = Ability must be unlocked during gameplay
--
-- For ability metadata (cooldown, stamina cost, etc.), see abilities.lua
-- ============================================================================
-- Generated by Project > Game Settings...

return {
  abilities = {]]

function M.generate(preset, source)
    local entries = M.ordered_abilities(source)
    local values = M.resolve(preset, source)
    local rows = { HEADER }
    local previous_category = false

    for _, entry in ipairs(entries) do
        if entry.category ~= previous_category then
            if previous_category ~= false then
                rows[#rows + 1] = ""
            end
            rows[#rows + 1] = "    -- " .. category_label(entry.category)
            previous_category = entry.category
        end
        rows[#rows + 1] = string.format("    %s = %s,", entry.id, tostring(values[entry.id]))
    end

    rows[#rows + 1] = "  }"
    rows[#rows + 1] = "}"
    rows[#rows + 1] = ""
    return table.concat(rows, "\n")
end

return M
