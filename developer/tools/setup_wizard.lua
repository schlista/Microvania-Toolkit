-- Generate the combat overrides file consumed by mvtk/combat/config.lua's
-- apply_attack_runtime_overrides. End-users can edit the generated file
-- directly to fine-tune hitbox sizes, damage, projectile speed, etc. without
-- ever touching code. The hot-reload key (F7) re-reads the merged result at
-- runtime.
local function generate_combat_overrides(preset)
  local normalized = CreatorSettings.from_controls(preset).overrides.combat or {}
  local function num(key, default)
    local v = preset[key]
    if type(v) ~= "number" then v = default end
    return v
  end

  local template = [[
-- ============================================================================
-- developer/config/combat_overrides.lua
-- ============================================================================
-- Game Settings-generated player combat tuning. Merged on top of the canonical
-- attack data in developer/config/combat_config.lua at runtime.
--
-- Edit any value here to tune the player's attacks. Hot-reload with F7 in
-- the running game (paired with Defold "Project -> Reload Resources") to
-- preview changes without restarting.
--
-- - melee_light / melee_heavy: per-attack damage and hitbox dimensions
-- - ranged: projectile damage and speed
-- ============================================================================
-- Generated by Project > Game Settings...

return {
  -- Player pixel units for these overrides; unitless version, safe 1 or 2.
  units_version = 2,
  combat = {
    melee_light = {
      damage = %s,
      cooldown = %s,
      hitbox = { width = %s, height = %s },
    },
    melee_heavy = {
      damage = %s,
      hitbox = { width = %s, height = %s },
    },
    ranged = {
      damage = %s,
      projectile_speed = %s,
    },
    parry = { window = %s },
    features = %s,
  },
}
]]

  return string.format(
    template,
    Number.fixed((normalized.melee_light or {}).damage or 1.0, 2),
    Number.general((normalized.melee_light or {}).cooldown or 0.18),
    tostring(num("light_hitbox_width", 210)),
    tostring(num("light_hitbox_height", 175)),
    Number.fixed((normalized.melee_heavy or {}).damage or 2.0, 2),
    tostring(num("heavy_hitbox_width", 269.5)),
    tostring(num("heavy_hitbox_height", 203)),
    Number.fixed((normalized.ranged or {}).damage or 1.0, 2),
    tostring((normalized.ranged or {}).projectile_speed or 2100),
    Number.general((normalized.parry or {}).window or 0.18),
    CreatorSettings.encode(normalized.features or {})
  )
end

