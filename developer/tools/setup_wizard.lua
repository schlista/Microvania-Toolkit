-- ANSI colors for terminal output
local COLOR = {
  RED = "\27[31m",
  CYAN = "\27[36m",
  RESET = "\27[0m",
}

local function color(text, col)
  return col .. text .. COLOR.RESET
end

local function print_error(message)
  print(color("❌ " .. message, COLOR.RED))
end

local function print_info(message)
  print(color("ℹ️  " .. message, COLOR.CYAN))
end

local function clamp_player_scale(value)
  if value == nil or value == "" then return 1.0 end
  local scale = tonumber(value)
  if not scale then
    print_info("Player size scale must be a number; using 1.0.")
    return 1.0
  end
  if scale < PlayerScale.MIN_SCALE then return PlayerScale.MIN_SCALE end
  if scale > PlayerScale.MAX_SCALE then return PlayerScale.MAX_SCALE end
  return scale
end

