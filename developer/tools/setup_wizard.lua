-- Generate neutral tile settings. Import Assets overwrites this mirror from
-- the imported tilesource art, which is the tile-size source of truth.
local function generate_tile_settings()
  local ok, result = pcall(TileSettingsWriter.validate_consistency, {
    root = ".",
    maps_dir = "developer/assets/tiled/maps",
    tilemaps_dir = "developer/assets/tiled/maps",
    tilesheets_dir = "developer/assets/tilesheets",
    tile_settings_path = "developer/config/tile_settings.lua",
  })
  if ok and result and result.primary then
    return TileSettingsWriter.generate(result.primary.width, result.primary.height, {
      source = result.primary.source or "imported tilesource art",
      generator = "Project > Game Settings...",
    })
  end
  return TileSettingsWriter.generate(nil, nil, {
    source = "neutral default until Import Assets reads imported tilesource art",
    generator = "Project > Game Settings...",
  })
end

