-- Non-interactive runner (for UI or scripting)
-- options = {
--   project_name = "My Game",
--   player_key = "balanced" | "fast" | "heavy" | 1/2/3,
--   biome_key = "forest" | "cave" | "castle" | 1/2/3,
--   player_scale = 1.0 (clamped to PlayerScale.MIN_SCALE..MAX_SCALE),
--   scale_movement = true|false (default true),
--   save_options = optional save_files options (used by headless tooling),
--   save = true|false (default true)
-- }
function M.run_noninteractive(options)
  options = options or {}
  local project_name = options.project_name

  local player_key = options.player_key or "balanced"
  if type(player_key) == "number" then
    player_key = (player_key == 2 and "fast") or (player_key == 3 and "heavy") or "balanced"
  end
  local biome_key = options.biome_key or options.biome or "forest"
  if type(biome_key) == "number" then
    biome_key = (biome_key == 2 and "cave") or (biome_key == 3 and "castle") or "forest"
  end

  local player_preset
  if player_key == "custom" and type(options.custom_player) == "table" then
    player_preset = CreatorSettings.copy(options.custom_player)
    player_preset.name = player_preset.name or "Custom"
  else
    player_preset = CreatorSettings.copy(PRESETS.player[player_key] or PRESETS.player.balanced)
  end
  local biome = PRESETS.biomes[biome_key] or PRESETS.biomes.forest
  local player_scale = clamp_player_scale(options.player_scale or player_preset.player_scale)
  local scale_movement = options.scale_movement
  if scale_movement == nil then scale_movement = player_preset.scale_movement end
  scale_movement = scale_movement ~= false

  local out = {
    project_name = project_name,
    tile_settings = generate_tile_settings(),
    player_settings = generate_player_settings(player_preset, player_scale, scale_movement),
    ability_defaults = generate_ability_defaults(player_preset),
    combat_overrides = generate_combat_overrides(player_preset),
    first_room = generate_first_room(biome_key),
    readme = generate_readme(),
    biome = biome_key,
    player_key = player_key,
    player_preset = player_preset,
    biome_preset = biome,
    player_scale = player_scale,
    scale_movement = scale_movement,
    custom_player = (player_key == "custom") and player_preset or nil,
    previous_overrides = options.previous_overrides,
    requested_document = options.creator_document,
    expected_document = options.expected_document,
    identity_proposal = options.identity_proposal,
    identity_choice = options.identity_choice,
    identity_review = options.identity_review,
    ownership_confirmed = options.ownership_confirmed,
  }

  local result = { ok = true, written = {}, out = out }

  -- Warn if existing imported art, Tiled exports, and the generated mirror are
  -- inconsistent. Import Assets owns the final tile_settings.lua value.
  local mismatches = M.detect_tile_size_mismatch()
  if #mismatches > 0 then
    result.tile_size_mismatches = mismatches
    print_error(string.format("Tile-size consistency warning: %d issue(s) found:", #mismatches))
    for _, m in ipairs(mismatches) do
      print("  - " .. tostring(m.message or m.name or m.source))
    end
    print_info("Run Prepare & Check after updating art or Tiled exports so tile_settings.lua is regenerated from the art.")
  end

  if options.save ~= false then
    print(string.format(
      "[SETUP_WIZARD_FILES] run_noninteractive save project=%s player=%s",
      tostring(project_name),
      tostring(player_key)
    ))
    local ok, written_or_err, err_info = pcall(M.save_files, out, options.save_options)
    if ok and written_or_err then
      result.written = written_or_err or {}
      print("[SETUP_WIZARD_FILES] save_files wrote " .. tostring(#result.written) .. " files")
    elseif ok and not written_or_err then
      -- save_files returned nil on rollback path; err_info is the diagnostic.
      result.ok = false
      result.error = (err_info and err_info.message) or "save_files rolled back"
      result.rollback = err_info
      print("[SETUP_WIZARD_FILES] save_files rolled back: " .. tostring(result.error))
    else
      result.ok = false
      result.error = written_or_err
      print("[SETUP_WIZARD_FILES] save_files failed: " .. tostring(written_or_err))
    end
  end

  return result
end

-- ----------------------------------------------------------------------------
-- Tile-size consistency detection
-- ----------------------------------------------------------------------------
-- Validate imported tilesources, Tiled exports, and tile_settings.lua against
-- each other. Returns a list of user-facing issue records. The function is
-- best-effort and never blocks setup; Import Assets is the canonical repair.
function M.detect_tile_size_mismatch(opts)
  opts = type(opts) == "table" and opts or {}
  local ok, result = pcall(TileSettingsWriter.validate_consistency, {
    root = opts.root or ".",
    maps_dir = opts.maps_dir or "developer/assets/tiled/maps",
    tilemaps_dir = opts.tilemaps_dir or "developer/assets/tiled/maps",
    tilesheets_dir = opts.tilesheets_dir or "developer/assets/tilesheets",
    tile_settings_path = opts.tile_settings_path or "developer/config/tile_settings.lua",
    require_tile_settings_match = true,
  })
  local mismatches = {}
  if not ok then
    return {
      {
        name = "tile_size_validator",
        message = "Tile-size validator failed: " .. tostring(result),
      }
    }
  end

  for _, message in ipairs(TileSettingsWriter.format_validation_messages(result)) do
    mismatches[#mismatches + 1] = {
      name = "tile_size_consistency",
      message = message,
    }
  end
  return mismatches, result
end

function M.write_tile_settings_from_art(opts)
  opts = type(opts) == "table" and opts or {}
  local result = TileSettingsWriter.write_project_settings_from_art({
    root = opts.root or ".",
    room_ids = opts.room_ids,
    maps_dir = opts.maps_dir or "developer/assets/tiled/maps",
    tilemaps_dir = opts.tilemaps_dir or "developer/assets/tiled/maps",
    tilesheets_dir = opts.tilesheets_dir or "developer/assets/tilesheets",
    tile_settings_path = opts.tile_settings_path or "developer/config/tile_settings.lua",
    write_if_changed = opts.write_if_changed,
    generator = opts.generator or "Import Assets",
  })
  return result
end

