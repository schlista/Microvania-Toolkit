M.SECRET_ROOMS_PATH = "developer/config/secret_rooms.lua"

-- Secret rooms name rooms the reset deletes. Keep the documented file, empty.
-- Returns {} when the project has no secret_rooms.lua, or nil and a reason.
function M.build_secret_rooms_files(read_text)
    assert(type(read_text) == "function", "secret rooms reset requires a text reader")
    local text = read_text(M.SECRET_ROOMS_PATH)
    if type(text) ~= "string" then return {} end
    local emptied, err = require("mvtk.editor.config_table_reset").empty(text)
    if not emptied then return nil, M.SECRET_ROOMS_PATH .. ": " .. tostring(err) end
    return { { path = M.SECRET_ROOMS_PATH, content = emptied } }
end

function M.build_empty_music_files(read_text)
    assert(type(read_text) == "function", "empty music reset requires a text reader")
    local tracks = {}
    local outputs = {}

    local function required(path)
        local text = read_text(path)
        if type(text) ~= "string" then
            return nil, "Could not read required music wiring file: " .. path
        end
        return text
    end

    local go_text, go_error = required("developer/game/audio/audio_controller.go")
    if not go_text then return nil, go_error end
    local rewritten_go, rewrite_go_error = MusicSync.rewrite_audio_go(go_text, tracks)
    if not rewritten_go then return nil, rewrite_go_error end
    outputs[#outputs + 1] = {
        path = "developer/game/audio/audio_controller.go",
        content = rewritten_go,
    }

    local script_text, script_error = required("mvtk/audio/audio_controller.script")
    if not script_text then return nil, script_error end
    local rewritten_script, rewrite_script_error = MusicSync.rewrite_music_table(script_text, tracks)
    if not rewritten_script then return nil, rewrite_script_error end
    rewritten_script, rewrite_script_error = MusicSync.rewrite_music_map(rewritten_script, {})
    if not rewritten_script then return nil, rewrite_script_error end
    outputs[#outputs + 1] = {
        path = "mvtk/audio/audio_controller.script",
        content = rewritten_script,
    }

    outputs[#outputs + 1] = {
        path = "developer/config/music_tracks_generated.lua",
        content = MusicSync.generate_music_tracks_manifest(tracks),
    }

    for _, path in ipairs({
        "MVTK.tiled-project",
        "tiled/custom_types/MV_ToolKit.custom-types.json",
        "tiled/custom_types/MV_ToolKit.custom-types.array.json",
    }) do
        local text, read_error = required(path)
        if not text then return nil, read_error end
        for _, enum_name in ipairs({ "music_tracks", "boss_music_tracks" }) do
            local rewritten, enum_error = MusicSync.rewrite_music_tracks_enum(
                text, tracks, enum_name)
            if not rewritten then return nil, enum_error .. " in " .. path end
            text = rewritten
        end
        outputs[#outputs + 1] = { path = path, content = text }
    end

    return outputs
end

-- Reset/package staging must restore geometry before discarding scale overrides.
function M.build_player_files(read_text)
    local baseline = read_text("developer/config/player_settings.lua")
    if not baseline then return {} end
    local Model = require "mvtk.core.creator_settings_model"
    -- Editor Lua provides load; runtime/headless Lua 5.1 uses loadstring.
    local load_config = loadstring or load
    local player = assert(load_config(baseline, "@developer/config/player_settings.lua"))()
    local previous = Model.copy(player)
    local creator = read_text("developer/config/creator_settings.lua")
    if creator then
        local doc = Model.load_document(assert(load_config(creator, "@developer/config/creator_settings.lua"))(), player)
        if doc.published then Model.merge(previous, doc.overrides.player or {}) end
    end
    local files = require("mvtk.editor.player_scale_writer").stage({
        base="developer", read=read_text, player=player, previous=previous,
    })
    for _, file in ipairs(files) do file.path = "developer/" .. file.path end
    local atlas=read_text("developer/assets/atlas/player.atlas")
    if atlas and atlas:find("/player_import/",1,true) then
        local names={}; for name in atlas:gmatch('id:%s*"([%w_]+)"') do names[#names+1]=name end
        local rows={}; for _,name in ipairs(names) do rows[#rows+1]='animations { id: "'..name..'" images { image: "/builtins/graphics/particle_blob.png" } playback: PLAYBACK_LOOP_FORWARD }' end
        files[#files+1]={path="developer/assets/atlas/player.atlas",content=table.concat(rows,"\n").."\n"}
    end
    return files
end

function M.repoint_prefab_tilemap(text)
    if type(text) ~= "string" then return text, false end
    local replacement = 'tile_set: "/developer/assets/tilesheets/defold_sample.tilesource"'
    local updated, count = text:gsub('tile_set:%s*"[^"]*"', replacement, 1)
    return updated, count > 0 and updated ~= text
end

