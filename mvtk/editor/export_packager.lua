-- mvtk/editor/export_packager.lua
-- Standalone project export packaging and game.project patch helpers.

local M = {}

local _deps = {}
local ROOT = "."
local DIR_SEP = package.config:sub(1, 1)

function M.configure(opts)
    opts = opts or {}
    for k, v in pairs(opts) do
        _deps[k] = v
    end
    if opts.root ~= nil then ROOT = opts.root end
    if opts.dir_sep ~= nil then DIR_SEP = opts.dir_sep end
end

local function require_collab(name, value)
    assert(value, "mvtk.editor.export_packager: missing collaborator '" .. name
        .. "'; configure{} must supply it before export packaging runs")
    return value
end

local function call_dep(name, ...)
    return require_collab(name, _deps[name])(...)
end

local function info(msg) return call_dep("logger", msg) end
local function join(...) return call_dep("join", ...) end
local function read_text(...) return call_dep("read_text", ...) end
local function file_exists_any(...) return call_dep("file_exists_any", ...) end
local function list_dir_filesystem(...) return call_dep("list_dir_filesystem", ...) end

local profiler = setmetatable({}, {
    __index = function(_, key)
        local p = require_collab("profiler", _deps.profiler)
        return p[key]
    end,
})

function M.ensure_main_collection(content)
    if not content then
        return content
    end
    local replaced
    content, replaced = content:gsub("main_collection%s*=%s*[^\r\n]+", "main_collection = /developer/game/main.collectionc")
    if replaced == 0 then
        if content:find("%[bootstrap%]") then
            content = content:gsub("(%[bootstrap%][^\r\n]*)", "%1\nmain_collection = /developer/game/main.collectionc", 1)
        else
            content = content .. "\n[bootstrap]\nmain_collection = /developer/game/main.collectionc\n"
        end
    end
    return content
end

function M.ensure_native_extension_app_manifest(content)
    if not content then
        return content
    end
    if content:find("app_manifest%s*=") then
        return content
    end

    local manifest_path = join(ROOT, "game.appmanifest")
    if not file_exists_any(manifest_path) then
        return content
    end

    if content:find("%[native_extension%]") then
        content = content:gsub("(%[native_extension%][^\r\n]*)", "%1\napp_manifest = /game.appmanifest", 1)
    else
        content = content .. "\n[native_extension]\napp_manifest = /game.appmanifest\n"
    end
    return content
end

function M.prepare_export_game_project(content)
    -- Preserve the physics/engine selection that was actually playtested.
    -- Merely having an unused game.appmanifest must not select it on export.
    return content
end

local prepare_export_game_project = M.prepare_export_game_project

local function profile_step(label, fn)
    profiler.start(label)
    local ok, a, b, c = pcall(fn)
    profiler.stop(label)
    if not ok then
        error(a, 0)
    end
    return a, b, c
end

-- Some export steps invoke nested workflows that reset/report the shared profiler.
-- Snapshot and restore lets the outer export timing survive those inner runs.
local function profile_isolated_step(label, fn)
    profiler.start(label)
    local snapshot = profiler.snapshot()
    local ok, a, b, c = pcall(fn)
    profiler.restore(snapshot)
    profiler.stop(label)
    if not ok then
        error(a, 0)
    end
    return a, b, c
end


local export_skip_notice_shown = false

local function run_profiled_export(fn)
    profiler.reset()
    profiler.start("TOTAL export_game_assets()")
    local started = profiler.now()
    local ok, a, b = pcall(fn)
    profiler.stop("TOTAL export_game_assets()")
    local seconds = profiler.now() - started
    profiler.report()
    if not ok then
        error(a, 0)
    end
    return a, b, seconds
end

-- Only changed/generated bytes go through editor Lua's synchronizing writes.
-- The helper receives one validated plan for all directories and source copies.
local function export_plan(manifest)
    local copy, direct, directories, total_bytes = {}, {}, {}, 0
    for _, entry in ipairs(manifest.files) do
        total_bytes = total_bytes + #entry.content
        local target = manifest.originals[entry.path] == entry.content and copy or direct
        target[#target + 1] = entry
        local directory = entry.path:match("^(.*)/[^/]+$")
        while directory do
            directories[directory] = true
            directory = directory:match("^(.*)/[^/]+$")
        end
    end
    local sorted = {}
    for directory in pairs(directories) do sorted[#sorted + 1] = directory end
    table.sort(sorted)
    local lines = {"MVTK_EXPORT_PLAN_1"}
    for _, directory in ipairs(sorted) do lines[#lines + 1] = "D\t" .. directory end
    for _, entry in ipairs(copy) do lines[#lines + 1] = "C\t" .. entry.path end
    return copy, direct, table.concat(lines, "\n") .. "\n", total_bytes
end

-- The editor's LuaJ ignores %.Nf precision (prints every digit), so round with
-- integers; %d formatting behaves the same in LuaJ and desktop Lua.
local function decimal(value, places)
    local scale = 10 ^ places
    local scaled = math.floor(value * scale + 0.5)
    return string.format("%d.%0" .. places .. "d", math.floor(scaled / scale), scaled % scale)
end
local function mib(bytes) return decimal(bytes / (1024 * 1024), 2) end
M.decimal = decimal

local function write_checked(path, content)
    local handle, err = io.open(path, "wb")
    assert(handle, "Export staging directory missing for " .. path .. ": " .. tostring(err))
    local written, write_err = handle:write(content)
    local closed, close_err = handle:close()
    assert(written and closed, "Cannot finish export file: " .. path .. ": " .. tostring(write_err or close_err))
end

local function file_manifest(manifest, total_bytes)
    local lines = {"Microvania Export Game file manifest", "",
        "Published rooms: " .. manifest.room_count,
        "Project files: " .. #manifest.files, "File bytes: " .. total_bytes, "",
        "Open game.project in Defold, Fetch Libraries, then Build.",
        "This generated directory is replaced by the next Export Game.", ""}
    for _, warning in ipairs(manifest.warnings or {}) do lines[#lines + 1] = "Warning: " .. warning end
    for _, entry in ipairs(manifest.files) do
        lines[#lines + 1] = string.format("%s | %d bytes | %s", entry.path, #entry.content, entry.reason)
    end
    return table.concat(lines, "\n") .. "\n"
end

local function export_game_assets(opts)
    local forced = false
    local context = "automatic"

    if type(opts) == "table" then
        forced = opts.force == true
        context = opts.context or context
    end

    if not forced then
        if not export_skip_notice_shown then
            info("Standalone export skipped (context=" .. context .. ") - waiting for manual trigger.")
            export_skip_notice_shown = true
        end
        return false, "manual export not requested"
    end

    local function progress(message, running)
        info(message)
        if type(opts) == "table" and opts.progress then
            -- Closing a window must never interrupt publication or verification.
            local ok, err = pcall(opts.progress, message, running ~= false)
            if not ok then info("[EXPORT] Progress window update failed: " .. tostring(err)) end
        end
    end
    local ok, result, summary, seconds = pcall(run_profiled_export, function()
        export_skip_notice_shown = false
        info("Starting game export for standalone build...")
        progress("Checking the published world and game ID...")
        local Workspace = require "mvtk.editor.export_workspace"
        local workspace_opts = {dir_sep=DIR_SEP,
            run_process=require_collab("run_process", _deps.run_process)}
        -- Restore a prior successful export even when source validation below
        -- rejects this attempt. Recovery does not create or discard staging.
        profile_step("recover_export_workspace", function()
            Workspace.recover(ROOT, workspace_opts)
        end)
        -- Export only a complete settings/resource revision after interrupted saves.
        require("mvtk.editor.creator_settings_writer").recover(ROOT .. "/developer")
        local identity = require("developer.tools.project_identity").inspect(ROOT, {read=read_text})
        assert(identity.game_id ~= "", "Save once in Project > Game Settings... so this game has its permanent ID before exporting")
        info("[EXPORT] Game: " .. identity.title .. " | Permanent ID: " .. identity.game_id)

        -- Validate the actual published layout before changing room or export files.
        local published_text = read_text(join(ROOT, "developer/runtime/layout/world_layout.local.lua"))
            or read_text(join(ROOT, "developer/runtime/layout/world_layout.lua"))
        assert(published_text, "Publish a world with Prepare & Check (Tiled World) or Layout Export first")
        local published = assert((loadstring or load)(published_text, "@published_layout"))()
        local placed = {}
        for _,room in ipairs(published.rooms or {}) do placed[room.id] = true end
        assert(next(placed), "Publish a non-empty world with Prepare & Check (Tiled World) or Layout Export first")
        local world_files
        if published.source and published.source.kind=="tiled" then
            world_files={};for _,room in ipairs(published.rooms) do world_files[#world_files+1]=room.id..".lua" end
        end
        progress("Checking room relationships...")
        require("developer.tools.relationship_project").require_valid({
            root=ROOT, list_dir_filesystem=list_dir_filesystem, published_rooms=placed,
            read=read_text, log=info, publish_report=false, files=world_files,
        })
        progress("Checking progression...")
        require("developer.tools.progression_project").require_valid({
            root=ROOT,layout=published,list_dir_filesystem=list_dir_filesystem,
            read=read_text,log=info,publish_report=false,files=world_files,
        })

        -- Package only the revision the designer explicitly published. Generating
        -- rooms here would mix a new room revision with an older minimap/layout.
        progress("Confirming the published revision is current...")
        require("developer.tools.preparation").require_published({root=ROOT,
            list_dir_filesystem=list_dir_filesystem,read=read_text})

        local Manifest = require "mvtk.editor.export_manifest"
        progress("Selecting runtime files...")
        local manifest = profile_step("select_runtime_dependencies", function()
            return Manifest.build({root=ROOT, read=read_text, list=list_dir_filesystem,
                layout=published, layout_text=published_text,
                prepare_project=prepare_export_game_project})
        end)
        local copy, direct, plan, total_bytes = export_plan(manifest)
        progress(string.format("Selected %d files (%s MiB) for %d rooms.",
            #manifest.files, mib(total_bytes), manifest.room_count))
        progress("Preparing the staging folder...")
        local stage = profile_step("prepare_export_workspace", function()
            return Workspace.prepare(ROOT, workspace_opts)
        end)
        profile_step("write_standalone_project", function()
            local plan_path = join(ROOT, ".build/export-plan.txt")
            profile_step("write_export_plan", function()
                write_checked(plan_path, plan)
                assert(read_text(plan_path) == plan, "Export file verification failed: " .. plan_path)
            end)
            progress(string.format("Copying %d unchanged files...", #copy))
            profile_step("stage_unchanged_files", function()
                assert(Workspace.stage(ROOT, plan_path, workspace_opts) == #copy,
                    "Export workspace helper copied an unexpected number of files")
            end)
            progress(string.format("Writing %d standalone files...", #direct + 1))
            profile_step("write_changed_files", function()
                for _, entry in ipairs(direct) do write_checked(stage .. "/" .. entry.path, entry.content) end
            end)
            progress("Verifying staged files...")
            profile_step("verify_staged_files", function()
                for _, entry in ipairs(manifest.files) do
                    local matches = read_text(stage .. "/" .. entry.path) == entry.content
                    if manifest.originals[entry.path] == entry.content then
                        assert(matches, "Project changed during export: " .. entry.path .. ". Retry Export Game.")
                    else
                        assert(matches, "Export file verification failed: " .. stage .. "/" .. entry.path)
                    end
                end
            end)
            -- Last staged write; copied and patched project bytes are already checked.
            local path, content = stage .. "/EXPORT_MANIFEST.txt", file_manifest(manifest, total_bytes)
            write_checked(path, content)
            assert(read_text(path) == content, "Export file verification failed: " .. path)
        end)
        progress("Checking that the project did not change during export...")
        profile_step("verify_export_revision", function()
            for path, original in pairs(manifest.originals) do
                local expected = original ~= false and original or nil
                assert(read_text(join(ROOT,path)) == expected,
                    "Project changed during export: " .. path .. ". Retry Export Game.")
            end
            for path, inventory in pairs(manifest.inventories or {}) do
                local dirs, files = list_dir_filesystem(join(ROOT,path), {force_process=true})
                assert(Manifest.directory_signature(dirs,files) == inventory,
                    "Resource directory changed during export: " .. path .. ". Retry Export Game.")
            end
            require("developer.tools.preparation").require_published({root=ROOT,
                list_dir_filesystem=list_dir_filesystem,read=read_text})
        end)
        progress("Publishing export/...")
        profile_step("publish_standalone_project", function()
            local _, warning = Workspace.publish(ROOT, workspace_opts)
            if warning then info("[EXPORT] " .. warning) end
        end)
        info(string.format("[EXPORT] Published %d rooms, %d files (%s MiB).",
            manifest.room_count, #manifest.files, mib(total_bytes)))
        info("[EXPORT] File selection: export/EXPORT_MANIFEST.txt")
        for _, warning in ipairs(manifest.warnings or {}) do info("[EXPORT] Warning: " .. warning) end
        info("EXPORT COMPLETED: Open export/game.project in Defold, Fetch Libraries, then Build.")
        return true, {rooms=manifest.room_count, files=#manifest.files, bytes=total_bytes, warnings=manifest.warnings}
    end)
    if not ok then
        progress("Export failed: " .. tostring(result) .. "\nYour previous export/ folder was kept.", false)
        error(result, 0)
    end
    local lines = {string.format("Export complete in %s s: %d rooms, %d files, %s MiB.",
        decimal(seconds, 1), summary.rooms, summary.files, mib(summary.bytes)),
        "Next: open export/game.project in Defold, Fetch Libraries, then Build.",
        "File list: export/EXPORT_MANIFEST.txt"}
    for _, warning in ipairs(summary.warnings or {}) do lines[#lines + 1] = "Warning: " .. warning end
    progress(table.concat(lines, "\n"), false)
    return result
end


M.profile_step = profile_step
M.profile_isolated_step = profile_isolated_step
M.export_game_assets = export_game_assets

return M
