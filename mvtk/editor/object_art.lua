local M = {}
local q = function(s) return '"' .. P.proto_escape(s) .. '"' end
local n = P.fmt_num
local RECT = {
    collectible=true, ability=true, save_point=true, checkpoint=true, chest=true,
    npc=true, lore_item=true, sign=true, hint_stone=true, lever=true,
    health_station=true, energy_station=true, map_station=true, secret=true,
}
M.rectangle_types = RECT
local function optional(value)
    if value == nil or value == "" or value == "none" or value == 0 then return nil end
    return value
end
local function reference(value)
    if type(value) == "table" then value = value.id or value.value end
    local id = tonumber(value)
    return id and id > 0 and id or nil
end
local function properties(object) return F.flatten(object.properties or {}) end
local function read(c, path)
    return c.read_text(c.join(c.ROOT, (path:gsub("^/", ""))))
end
local function write(c, path, text)
    c.write_if_changed(c.join(c.ROOT, (path:gsub("^/", ""))), text)
end
local function set(doc, node, name, value)
    local field = R.one(node, name)
    if field then R.replace(doc, field, value)
    else R.insert(doc, node, name .. ": " .. (type(value)=="number" and n(value) or q(value))) end
end
local function vector(doc, node, name, x, y, z, w)
    local field = R.one(node, name)
    if field then R.remove(doc, field) end
    R.insert(doc, node, name .. " { x: " .. n(x) .. " y: " .. n(y) .. " z: " .. n(z) .. (w and " w: " .. n(w) or "") .. " }")
end
local function lua(value)
    if type(value) == "table" then
        local keys, rows = {}, {}
        for k in pairs(value) do keys[#keys+1] = k end
        table.sort(keys, function(a,b) return tostring(a)<tostring(b) end)
        for _, k in ipairs(keys) do rows[#rows+1] = "[" .. lua(k) .. "]=" .. lua(value[k]) end
        return "{" .. table.concat(rows, ",") .. "}"
    end
    if type(value) == "string" then return string.format("%q", value) end
    -- Lua 5.1 may share signed-zero constants when reloading this manifest.
    -- Both signs mean the same position/cooldown; persist one representation.
    if type(value)=="number" and value==0 then return "0" end
    return tostring(value)
end
local function manifest(c, updates, room)
    local path = "developer/config/object_art_generated.lua"
    local data = c.load_project_lua_table(path) or {}
    for id, spec in pairs(data) do if spec.room == room then data[id] = nil end end
    for id, spec in pairs(updates) do data[id] = spec end
    write(c, path, "-- Generated by Create Rooms. Author artwork and feedback in Tiled.\nreturn " .. lua(data) .. "\n")
end
function M.is_art(obj)
    local props = properties(obj)
    return obj.gid and (optional(props.owner_ref) ~= nil or obj.type == "object_art" or obj.class == "object_art")
end
local function canonical_path(value)
    local path = tostring(value):gsub("\\", "/"):gsub("/+", "/")
    local prefix = path:match("^[A-Za-z]:/") or path:match("^/") or ""
    local parts = {}
    for part in path:sub(#prefix + 1):gmatch("[^/]+") do
        if part == ".." then
            if #parts == 0 then return nil end
            parts[#parts] = nil
        elseif part ~= "." then
            parts[#parts + 1] = part
        end
    end
    return prefix .. table.concat(parts, "/")
end
local function resource(c, absolute)
    -- Tiled keeps legitimate maps/../tilesets/../backgrounds references.
    -- Resolve these before checking both the project and content boundaries.
    local path = canonical_path(absolute)
    local root = assert(canonical_path(c.ROOT)):gsub("/$", "")
    assert(path, "Artwork must be exported into developer/: " .. tostring(absolute))
    if root ~= "" and path:sub(1,#root+1):lower() == root:lower() .. "/" then
        path = path:sub(#root+1)
    end
    if path:match("^developer/") then path = "/" .. path end
    assert(path:match("^/developer/"), "Artwork must be exported into developer/: " .. path)
    return path
end
local function decode(gid)
    local g = tonumber(gid) or 0
    local h,v,d = g >= 2147483648, false, false
    if h then g=g-2147483648 end
    if g >= 1073741824 then v=true; g=g-1073741824 end
    if g >= 536870912 then d=true; g=g-536870912 end
    if g >= 268435456 then g=g-268435456 end
    return g,h,v,d
end
local function tilesets(c, map, source)
    local sets = {}
    for _, ts in ipairs(map.tilesets or {}) do
        sets[#sets+1] = { firstgid=ts.firstgid or 1, source=ts, meta=c.get_tileset_meta(ts, source) }
    end
    table.sort(sets, function(a,b) return a.firstgid < b.firstgid end)
    return sets
end
function M.catalog(c, rooms)
    local items, atlas, first, identities = {}, {}, nil, {}
    for _, room in ipairs(rooms or {}) do
        local map, source = c.load_tiled_export(room)
        if map then
            for _, entry in ipairs(c.flatten_tiled_layers(map.layers)) do
                for _, obj in ipairs(entry.layer.objects or {}) do
                    local id=optional(properties(obj).collectible_id)
                    if id then
                        local owner=room .. ":" .. tostring(obj.id)
                        assert(not identities[id],"Duplicate collectible_id '" .. id .. "': " .. tostring(identities[id]) .. " and " .. owner)
                        identities[id]=owner
                    end
                end
            end
            for _, ts in ipairs(tilesets(c,map,source)) do
                for id, props in pairs(ts.meta.tile_properties or {}) do
                    -- Named decoration can also be selected by a rectangle's
                    -- art_item. It need not declare collectible behavior.
                    local item = optional(props.item_type)
                        or (ts.meta.tile_images[id] and optional(props.asset_name))
                    if item then
                        assert(tostring(item):match("^[%w_]+$"), "Invalid catalog item_type/asset_name: " .. tostring(item))
                        local image=assert(ts.meta.tile_images[id],"Item catalog entries need collection images")
                        image=resource(c,image)
                        assert(not items[item] or items[item].image==image,"Conflicting Tiled catalog images for " .. item)
                        if not items[item] then
                            local w,h=c.get_png_dimensions(image)
                            local authored_w,authored_h=tonumber(props.item_width),tonumber(props.item_height)
                            if authored_w and authored_w>0 then w=authored_w end
                            if authored_h and authored_h>0 then h=authored_h end
                            items[item]={image=image,width=w,height=h,animation=item,consume_effect=optional(props.consume_effect)}
                        end
                    end
                end
            end
        end
    end
    local keys={}
    for id in pairs(items) do keys[#keys+1]=id end
    table.sort(keys)
    for _, id in ipairs(keys) do
        first=first or id
        atlas[#atlas+1]='animations { id: ' .. q(id) .. ' images { image: ' .. q(items[id].image) .. ' } playback: PLAYBACK_LOOP_FORWARD fps: 1 }'
    end
    local path="/developer/game/prefabs/collectible_generic.go"
    local text=M.strip(assert(read(c,path)))
    -- Remove historical sample effects. Optional feedback is compiled from
    -- the catalog instead of depending on developer/examples resources.
    local doc=R.parse(text)
    for _, field in ipairs(R.all(doc.root,"components")) do
        if tostring(R.value(field.node,"component")):match("%.particlefx$") then R.remove(doc,field) end
    end
    text=R.tidy(R.render(doc))
    if first then
        local atlas_path="/developer/assets/tiled/item_catalog.atlas"
        write(c,atlas_path,table.concat(atlas,"\n") .. "\nextrude_borders: 2\n")
        text=text .. '\nembedded_components { id: "sprite" type: "sprite" data: ' .. q('default_animation: ' .. q(first) .. ' size_mode: SIZE_MODE_MANUAL size { x: ' .. n(items[first].width) .. ' y: ' .. n(items[first].height) .. ' } textures { sampler: "texture_sampler" texture: ' .. q(atlas_path) .. ' }') .. ' }\n'
    end
    local effects=c.load_project_lua_table("developer/config/particle_effects.lua") or {}
    for _, id in ipairs(keys) do
        local item=items[id]
        if item.consume_effect then
            local fx=effects.effects and effects.effects[item.consume_effect]
            assert(fx and read(c,fx),"Unknown item consume_effect: " .. item.consume_effect)
            assert(not read(c,fx):find("PLAY_MODE_LOOP",1,true),"Drop feedback must be one-shot: " .. fx)
            item.effect_component="drop_fx_" .. id
            text=text .. 'components { id: ' .. q(item.effect_component) .. ' component: ' .. q(fx) .. ' }\n'
        end
    end
    write(c,path,text)
    local settings=c.load_project_lua_table("developer/config/object_art.lua") or {}
    local currency=items[settings.currency_item]
    local coin_path="/developer/game/prefabs/loot_coin.go"
    local coin_source=read(c,coin_path)
    if coin_source then
        local coin=M.strip(coin_source)
        local coin_doc=R.parse(coin)
        for _, field in ipairs(R.all(coin_doc.root,"components")) do
            if R.value(field.node,"id")=="consume_fx" then R.remove(coin_doc,field) end
        end
        coin=R.tidy(R.render(coin_doc))
        if currency then
            coin=coin .. '\nembedded_components { id: "sprite" type: "sprite" data: ' .. q('default_animation: ' .. q(currency.animation) .. ' size_mode: SIZE_MODE_MANUAL size { x: ' .. n(currency.width) .. ' y: ' .. n(currency.height) .. ' } textures { sampler: "texture_sampler" texture: "/developer/assets/tiled/item_catalog.atlas" }') .. ' }\n'
            if currency.consume_effect then
                coin=coin .. 'components { id: "consume_fx" component: ' .. q(effects.effects[currency.consume_effect]) .. ' }\n'
            end
        end
        write(c,coin_path,coin)
    end
    write(c,"developer/config/item_art_generated.lua","-- Generated from collection-image tiles with item_type or asset_name. Edit the tiles in Tiled.\nreturn " .. lua(items) .. "\n")
end
local function tile(sets, gid)
    local g,h,v,d = decode(gid)
    for i=#sets,1,-1 do
        local ts=sets[i]
        if g>=ts.firstgid then return ts, g-ts.firstgid,h,v,d end
    end
    error("Unresolved Tiled image GID " .. tostring(gid))
end
local function image_info(c, sets, obj)
    local ts,id,h,v,d = tile(sets,obj.gid)
    local image = ts.meta.tile_images[id]
    if not image and not ts.meta.collection and ts.meta.image then
        local meta = ts.meta
        local tilecount=tonumber(meta.tilecount)
        if not tilecount or tilecount<1 then
            local iw,ih=meta.imagewidth,meta.imageheight
            if not iw or not ih then iw,ih=c.get_png_dimensions(meta.image) end
            assert(iw and ih,"Could not read sheet image dimensions: " .. tostring(meta.image))
            local margin,spacing=meta.margin or 0,meta.spacing or 0
            local columns=math.floor((iw-2*margin+spacing)/(meta.tilewidth+spacing))
            local rows=math.floor((ih-2*margin+spacing)/(meta.tileheight+spacing))
            tilecount=columns*rows
        end
        assert(tilecount>=1 and tilecount%1==0,"Invalid sheet tile count: " .. tostring(meta.image))
        local frames = {}
        local animation = meta.tile_animations and meta.tile_animations[id]
        for index, frame_id in ipairs(animation and animation.frames or {id}) do
            local props = meta.tile_properties and meta.tile_properties[frame_id] or {}
            frames[#frames+1] = { id="tile_" .. frame_id,
                tile=frame_id+1, duration=math.max(1, tonumber(animation and animation.durations_ms[index]) or 100)/1000,
                hazard_active=props.hazard_active }
        end
        return {image=resource(c,meta.image),width=meta.tilewidth,height=meta.tileheight,
            sheet=true,tilecount=tilecount,frames=frames,margin=meta.margin or 0,spacing=meta.spacing or 0,
            h=h,v=v,d=d,alignment=meta.objectalignment or "bottomleft"}
    end
    assert(image, "Object " .. tostring(obj.id) .. ": choose an image from a collection-of-images tileset")
    local w,ht = c.get_png_dimensions(image)
    assert(w and ht, "Could not read image dimensions: " .. tostring(image))
    return { image=resource(c,image), width=w, height=ht, h=h, v=v, d=d,
        alignment=ts.meta.objectalignment or ts.source.objectalignment or "bottomleft" }
end
local ALIGN = { topleft={0,0}, top={.5,0}, topright={1,0}, left={0,.5}, center={.5,.5}, right={1,.5}, bottomleft={0,1}, bottom={.5,1}, bottomright={1,1}, unspecified={0,1} }
local function center(obj, info, mapheight)
    local w,h=tonumber(obj.width) or 0,tonumber(obj.height) or 0
    if w<=0 then w=info and info.width or 0 end
    if h<=0 then h=info and info.height or 0 end
    local align=info and (ALIGN[info.alignment] or ALIGN.bottomleft) or ALIGN.topleft
    local a=math.rad(tonumber(obj.rotation) or 0)
    local dx,dy=w*(.5-align[1]),h*(.5-align[2])
    return obj.x+dx*math.cos(a)-dy*math.sin(a),mapheight-obj.y-dx*math.sin(a)-dy*math.cos(a),w,h,-a
end
-- Fold tile defaults into an instance without changing its ID. Explicit object
-- properties win. Native object references remain numeric IDs in Lua exports.
function M.prepare(c, map, source)
    local sets=tilesets(c,map,source)
    local function walk(layers)
        for _, layer in ipairs(layers or {}) do
            if layer.layers then walk(layer.layers) end
            for _, obj in ipairs(layer.objects or {}) do
                if obj.gid then
                    local ts,id=tile(sets,obj.gid)
                    local props={}
                    for k,v in pairs(ts.meta.tile_properties and ts.meta.tile_properties[id] or {}) do props[k]=v end
                    for k,v in pairs(properties(obj)) do props[k]=v end
                    obj.properties=props
                    if not optional(obj.type) then obj.type=optional(obj.class) or (ts.meta.tile_classes and ts.meta.tile_classes[id]) end
                    if obj.type=="item_art" then
                        obj.type="collectible"
                        props.collectible_type=props.collectible_type or props.item_type
                    end
                    if optional(props.owner_ref) then obj.type="object_art" end
                end
            end
        end
    end
    walk(map.layers)
    return sets
end
local function strip(source)
    local doc=R.parse(source)
    for _, field in ipairs(doc.root.entries) do
        if field.node and (field.name=="components" or field.name=="embedded_components") then
            local path=R.value(field.node,"component") or ""
            if R.value(field.node,"type")=="sprite" or path:match("%.sprite$")
                or path:match("animation_controller%.script$") then R.remove(doc,field) end
        end
    end
    return R.tidy(R.render(doc))
end
M.strip = strip
local function size_triggers(source,w,h)
    local doc=R.parse(source)
    for _, field in ipairs(R.all(doc.root,"embedded_components")) do
        if R.value(field.node,"type")=="collisionobject" then
            local data=R.one(field.node,"data")
            local co=R.parse(data.value)
            if R.value(co.root,"type")=="COLLISION_OBJECT_TYPE_TRIGGER" then
                for _, name in ipairs({"collision_shape","embedded_collision_shape"}) do
                    local old=R.one(co.root,name); if old then R.remove(co,old) end
                end
                R.insert(co,co.root,"embedded_collision_shape { shapes { shape_type: TYPE_BOX position { } rotation { w: 1.0 } index: 0 count: 3 } data: " .. n(w/2) .. " data: " .. n(h/2) .. " data: 5.0 }")
                R.replace(doc,data,R.render(co))
                vector(doc,field.node,"position",0,0,0)
            end
        end
    end
    return R.render(doc)
end
M.size_triggers = size_triggers
local function instance(id,proto,x,y,z,angle)
    return "instances { id: " .. q(id) .. " prototype: " .. q(proto) .. " position { x: " .. n(x) .. " y: " .. n(y) .. " z: " .. n(z) .. " } rotation { z: " .. n(math.sin((angle or 0)/2)) .. " w: " .. n(math.cos((angle or 0)/2)) .. " } }\n"
end
local function make_image(c,id,info,w,h,atlas,motion)
    local base="/developer/rooms/generated/" .. id
    if info.sheet then
        local header={"image: " .. q(info.image),"tile_width: " .. n(info.width),
            "tile_height: " .. n(info.height),"tile_margin: " .. n(info.margin),
            "tile_spacing: " .. n(info.spacing),"extrude_borders: 2"}
        local key=table.concat(header,"\n") .. "\n" .. tostring(info.tilecount)
        local texture=atlas.sheets[key]
        if not texture then
            -- All grid frames and flip variants share one immutable texture,
            -- even when different rooms use different subsets of this sheet.
            -- Timing and hazard markers remain on each instance's frame list.
            local rows={table.concat(header,"\n")}
            for tile_id=0,info.tilecount-1 do
                for _,flip in ipairs({{"",0,0},{"_h",1,0},{"_v",0,1},{"_hv",1,1}}) do
                    rows[#rows+1]="animations { id: " .. q("tile_" .. tile_id .. flip[1]) ..
                        " start_tile: " .. (tile_id+1) .. " end_tile: " .. (tile_id+1) ..
                        " playback: PLAYBACK_LOOP_FORWARD fps: 1 flip_horizontal: " .. flip[2] ..
                        " flip_vertical: " .. flip[3] .. " }"
                end
            end
            texture=SharedAtlas.store_tilesource(c,table.concat(rows,"\n") .. "\n")
            atlas.sheets[key]=texture
        end
        local suffix=(info.h and "_h" or "") .. (info.v and (info.h and "v" or "_v") or "")
        for _,frame in ipairs(info.frames) do
            assert(frame.tile>=1 and frame.tile<=info.tilecount,"Artwork frame is outside its sheet: " .. id)
            frame.id=frame.id .. suffix
        end
        local sprite="default_animation: " .. q(info.frames[1].id) .. " size_mode: SIZE_MODE_MANUAL size { x: " ..
            n(info.d and h or w) .. " y: " .. n(info.d and w or h) ..
            " } textures { sampler: \"texture_sampler\" texture: " .. q(texture) .. " }"
        write(c,base .. ".go","embedded_components { id: \"art\" type: \"sprite\" data: " .. q(sprite) .. " }\n" .. (motion or ""))
        return base .. ".go"
    end
    -- Explicit one-frame animation works on the installed engine, including
    -- runtime drop atlases. A diagonal flag swaps axes before H/V flips.
    local key=info.image .. ":" .. tostring(info.h==true) .. ":" .. tostring(info.v==true)
    local animation=atlas.images[key]
    if not animation then
        animation="image_" .. tostring(#atlas.rows+1)
        atlas.images[key]=animation
        atlas.rows[#atlas.rows+1]="animations { id: " .. q(animation) .. " images { image: " .. q(info.image) .. " } playback: PLAYBACK_LOOP_FORWARD fps: 1 flip_horizontal: " .. (info.h and "1" or "0") .. " flip_vertical: " .. (info.v and "1" or "0") .. " }"
    end
    -- Resolve the shared atlas after collecting this room's animations. The
    -- gameobjects stay per-instance and editable; only their texture is shared.
    atlas.sprites[#atlas.sprites+1]={path=base .. ".go",animation=animation,
        width=info.d and h or w,height=info.d and w or h,motion=motion}
    return base .. ".go"
end
local function effect_components(c,props,spec,catalog)
    local effects,rows={},{}
    local consumed=optional(props.consume_effect)
    local interacted=optional(props.interact_effect)
    -- Maps authored before interact_effect existed fall back to particle_id.
    -- That legacy field often names an ambient loop; skip it with a warning
    -- instead of failing Create Rooms for the whole project.
    local legacy_interacted=false
    if props.interact_effect==nil then
        interacted=optional(props.particle_id)
        legacy_interacted=interacted~=nil
    end
    for _, pair in ipairs({{"collected",consumed},{"destroyed",consumed},{"interacted",interacted},{"opened",interacted}}) do
        local event,id=pair[1],pair[2]
        local path=id and catalog.effects and catalog.effects[id]
        local text=type(path)=="string" and read(c,path) or nil
        local legacy=legacy_interacted and (event=="interacted" or event=="opened")
        if id and legacy and (not text or text:find("PLAY_MODE_LOOP",1,true)) then
            if c.info then
                c.info("[OBJECT_ART] WARNING: legacy particle_id '" .. tostring(id) .. "' is "
                    .. (text and "a looping effect" or "not in developer/config/particle_effects.lua")
                    .. ", so it was not used as the " .. event
                    .. " effect. Set interact_effect to a one-shot effect in Tiled.")
            end
            id=nil
        end
        if id then
            assert(type(path)=="string" and text,"Unknown interaction particle effect: " .. tostring(id))
            assert(not text:find("PLAY_MODE_LOOP",1,true),"Interaction particles must be one-shot: " .. path)
            local comp="fx_" .. event
            effects[event]=comp
            rows[#rows+1]="components { id: " .. q(comp) .. " component: " .. q(path) .. " position { x: " .. n(props.effect_offset_x or 0) .. " y: " .. n(props.effect_offset_y or 0) .. " } scale { x: " .. n(props.effect_scale or 1) .. " y: " .. n(props.effect_scale or 1) .. " z: 1.0 } }"
        end
    end
    spec.effects=effects
    spec.effect_cooldown=tonumber(props.effect_cooldown) or 0
    return table.concat(rows,"\n")
end
function M.finish(c,rid,map,source,collection)
    local effects=c.load_project_lua_table("developer/config/particle_effects.lua") or {}
    -- New prototypes may be queued in the Defold editor's creation batch.
    -- Commit before reading them; headless generation writes immediately.
    local sets=tilesets(c,map,source)
    local settings=c.load_project_lua_table("developer/config/object_art.lua") or {}
    local mapheight=(map.height or 0)*(map.tileheight or 0)
    local objects,order={},{}
    for _, entry in ipairs(c.flatten_tiled_layers(map.layers)) do
        local layer=entry.layer
        if entry.visible~=false then
            for _, raw in ipairs(layer.objects or {}) do
                if raw.visible~=false then
                    local obj={}
                    for k,v in pairs(raw) do obj[k]=v end
                    obj.x=(obj.x or 0)+(entry.offsetx or 0); obj.y=(obj.y or 0)+(entry.offsety or 0)
                    obj.properties=properties(obj)
                    obj.kind=c.resolve_object_type(obj,c.load_object_type_set()) or obj.type
                    obj.layer=layer.name
                    obj.opacity=tonumber(entry.opacity) or 1
                    obj.parallaxx=(entry.parallaxx or 1)*(tonumber(V.property_value(raw,"parallaxx")) or 1)
                    obj.parallaxy=(entry.parallaxy or 1)*(tonumber(V.property_value(raw,"parallaxy")) or 1)
                    objects[obj.id]=obj; order[#order+1]=obj
                end
            end
        end
    end
    local doc=R.parse(collection)
    local instances={}
    for _, field in ipairs(R.all(doc.root,"instances")) do instances[R.value(field.node,"id")]=field.node end
    local updates,extra={},{}
    local atlas={images={},rows={},sprites={},sheets={}}
    for _, obj in ipairs(order) do
        local id=c.generated_object_id(rid,obj.kind,obj.id)
        local node=instances[id]
        if node and not V.uses_defold_sprite({},obj.kind) then
            local source_proto=R.one(node,"prototype")
            local source_text=assert(read(c,source_proto.value),"Missing baked prototype " .. source_proto.value)
            local text=strip(source_text)
            local info=obj.gid and image_info(c,sets,obj) or nil
            local x,y,w,h,a=center(obj,info,mapheight)
            local spec={room=rid,owner=id,art={}}
            if RECT[obj.kind] and w>0 and h>0 then
                text=size_triggers(text,w,h)
                vector(doc,node,"position",x,y,0)
                vector(doc,node,"rotation",0,0,math.sin(a/2),math.cos(a/2))
                local scale=R.one(node,"scale3"); if scale then R.remove(doc,scale) end
                spec.width,spec.height,spec.angle=w,h,a
                if obj.kind=="collectible" or obj.kind=="ability" then
                    for _, component in ipairs(R.all(node,"component_properties")) do
                        if R.value(component.node,"id")=="collectible" then
                            R.insert(doc,component.node,'properties { id: "authored_rectangle" value: "true" type: PROPERTY_TYPE_BOOLEAN }')
                        end
                    end
                end
            else
                local position=R.one(node,"position")
                x=position and R.value(position.node,"x") or 0
                y=position and R.value(position.node,"y") or 0
            end
            spec.x,spec.y=x,y
            local generated="/developer/rooms/generated/" .. id .. "_authored.go"
            write(c,generated,text); R.replace(doc,source_proto,generated)
            updates[id]=spec
        end
    end
    for _, obj in ipairs(order) do
        if obj.gid and not V.uses_defold_sprite({},obj.kind) then
            local props=obj.properties
            local owner_id=reference(props.owner_ref)
            local owner=owner_id and objects[owner_id] or obj
            local owner_key=owner and c.generated_object_id(rid,owner.kind,owner.id)
            local spec=updates[owner_key]
            if owner_id then assert(spec,"Artwork " .. obj.id .. ": owner_ref must select a gameplay object in this room") end
            if spec or (obj.kind == "object_art" and not owner_id) then
                local standalone = not spec
                spec = spec or { room=rid,art={} }
                assert(not reference(owner.properties.owner_ref),"Artwork ownership cannot form chains")
                local info=image_info(c,sets,obj)
                local x,y,w,h,a=center(obj,info,mapheight)
                -- Tiled diagonal is a transpose. Represent it using rotation
                -- plus a horizontal flip, then apply the remaining H/V flags.
                if info.d then
                    a=a-math.pi/2
                    info.h,info.v=not info.v,info.h
                end
                local art_id=rid .. "_art_" .. obj.id
                if standalone then
                    spec.owner,spec.x,spec.y=art_id,x,y
                    updates[owner_key]=spec
                end
                local motion
                if obj.parallaxx~=1 or obj.parallaxy~=1 then
                    assert(standalone,"Parallax artwork must be unowned decoration; keep gameplay-owned artwork at factor 1")
                    motion=require("hooks.core.parallax_bake").motion_script(map,x,y,obj.parallaxx,obj.parallaxy,false)
                end
                local proto=make_image(c,art_id,info,w,h,atlas,motion)
                local z=tonumber(props.art_z) or ((tonumber(settings.default_z) or 0.01) + #extra * 0.000001)
                extra[#extra+1]=instance(art_id,proto,x,y,z,a)
                spec.art[#spec.art+1]={id=art_id,state=optional(props.art_state) or "default",alpha=(tonumber(props.art_opacity) or 1)*obj.opacity,dx=x-spec.x,dy=y-spec.y,dz=standalone and 0 or z,frames=info.frames}
            end
        end
    end
    -- Rectangle pickups can inherit the same catalog image as runtime drops.
    local catalog=c.load_project_lua_table("developer/config/item_art_generated.lua") or {}
    for _, obj in ipairs(order) do
        local id=c.generated_object_id(rid,obj.kind,obj.id)
        local spec=updates[id]
        if spec and #spec.art==0 and not obj.gid then
            local item=optional(obj.properties.art_item)
            if not item and (obj.kind=="collectible" or obj.kind=="ability") then
                item=optional(obj.properties.collectible_type) or (optional(obj.properties.ability_id) and "ability_" .. obj.properties.ability_id)
            end
            local art=item and catalog[item]
            if art then
                local art_id=rid .. "_art_" .. obj.id
                local proto=make_image(c,art_id,{image=art.image},art.width,art.height,atlas)
                local z=tonumber(obj.properties.art_z) or tonumber(settings.default_z) or 0.01
                extra[#extra+1]=instance(art_id,proto,spec.x,spec.y,z)
                spec.art[1]={id=art_id,state="default",alpha=obj.opacity,dx=0,dy=0,dz=z}
            elseif optional(obj.properties.art_item) then
                error("Missing Tiled item catalog entry: " .. tostring(item))
            end
        end
    end
    for _, obj in ipairs(order) do
        local id=c.generated_object_id(rid,obj.kind,obj.id)
        local spec=updates[id]
        if spec then
            local fx=effect_components(c,obj.properties,spec,effects)
            local proto="/developer/rooms/generated/" .. id .. "_presentation.go"
            write(c,proto,'components { id: "presentation" component: "/mvtk/tiled/object_presentation.script" properties { id: "art_id" value: ' .. q(id) .. ' type: PROPERTY_TYPE_TEXT } }\n' .. fx .. '\n')
            extra[#extra+1]=instance(id .. "_presentation",proto,spec.x,spec.y,0)
        end
    end
    if #atlas.rows>0 then
        local path=SharedAtlas.store(c,table.concat(atlas.rows,"\n") .. "\nextrude_borders: 2\n")
        for _, art in ipairs(atlas.sprites) do
            local sprite="default_animation: " .. q(art.animation) .. " size_mode: SIZE_MODE_MANUAL size { x: " .. n(art.width) .. " y: " .. n(art.height) .. " } textures { sampler: \"texture_sampler\" texture: " .. q(path) .. " }"
            write(c,art.path,"embedded_components { id: \"art\" type: \"sprite\" data: " .. q(sprite) .. " }\n" .. (art.motion or ""))
        end
    end
    manifest(c,updates,rid)
    return R.render(doc) .. "\n" .. table.concat(extra)
end
return M
